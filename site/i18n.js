function i18nIsSupported(code) {
  return SUPPORTED_LANGS.some((l) => l.code === code);
}

/** String for a key: language -> English fallback -> key itself. */
function i18nT(key, lang) {
  const l = i18nIsSupported(lang) ? lang : DEFAULT_LANG;
  if (STRINGS[l] && STRINGS[l][key] !== undefined) return STRINGS[l][key];
  if (STRINGS.en[key] !== undefined) return STRINGS.en[key];
  return key;
}

function i18nGetLang() {
  try {
    const saved = typeof localStorage !== 'undefined' ? localStorage.getItem(LANG_STORAGE_KEY) : null;
    if (saved && i18nIsSupported(saved)) return saved;
  } catch (e) { /* ignore — default */ }
  return DEFAULT_LANG;
}

function i18nSetLang(code) {
  const next = i18nIsSupported(code) ? code : DEFAULT_LANG;
  try {
    if (typeof localStorage !== 'undefined') localStorage.setItem(LANG_STORAGE_KEY, next);
  } catch (e) { /* ignore */ }
  return next;
}

function i18nDir(code) {
  const found = SUPPORTED_LANGS.find((l) => l.code === code);
  return found ? found.dir : 'ltr';
}

const i18nApi = {
  SUPPORTED_LANGS, DEFAULT_LANG, LANG_STORAGE_KEY, STRINGS,
  isSupported: i18nIsSupported, t: i18nT, getLang: i18nGetLang,
  setLang: i18nSetLang, dir: i18nDir,
};

if (typeof module !== 'undefined' && module.exports) {
  module.exports = i18nApi;
} else {
  window.UdyamSetu = window.UdyamSetu || {};
  window.UdyamSetu.i18n = i18nApi;
}
